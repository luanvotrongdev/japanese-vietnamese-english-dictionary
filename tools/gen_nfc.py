"""Generates src/nfc_table.zig, the data src/text.zig uses for NFC.

Usage: python -I tools/gen_nfc.py > src/nfc_table.zig && zig fmt src/nfc_table.zig

Covers combining marks U+0300-U+036F only: the accents of Latin (Vietnamese
included), Greek and Cyrillic letters. Japanese text is never changed.
"""

import sys
import unicodedata

MARKS = range(0x0300, 0x0370)

ccc = [unicodedata.combining(chr(m)) for m in MARKS]

# Marks NFC replaces with other marks (U+0341 -> U+0301, from some Vietnamese
# keyboards), as full decompositions.
mark_map = []
for m in MARKS:
    nfd = unicodedata.normalize('NFD', chr(m))
    if nfd != chr(m):
        mark_map.append((m, [ord(c) for c in nfd]))

# Canonical pairs (base, mark) -> precomposed letter, minus composition
# exclusions: exactly the pairs NFC composes.
compositions = []
for cp in range(0x110000):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith('<'):
        continue
    parts = [int(p, 16) for p in d.split()]
    if len(parts) != 2 or parts[1] not in MARKS:
        continue
    if unicodedata.normalize('NFC', chr(parts[0]) + chr(parts[1])) != chr(cp):
        continue
    compositions.append((parts[0], parts[1], cp))
compositions.sort()

# Precomposed letter -> (base, mark), for re-sorting marks before composing.
decompositions = sorted((cp, base, mark) for base, mark, cp in compositions)

out = sys.stdout
out.write('//! Generated by tools/gen_nfc.py from Unicode %s. Do not edit.\n\n' % unicodedata.unidata_version)
out.write('pub const Pair = struct { a: u21, b: u21, c: u21 };\n\n')
out.write('/// Canonical combining class of U+0300 + i.\n')
out.write('pub const combining_class = [_]u8{ %s };\n\n' % ', '.join(map(str, ccc)))
out.write('/// Marks NFC replaces: mark -> replacement marks.\n')
out.write('pub const mark_replacements = [_]struct { mark: u21, with: []const u21 }{\n')
for m, repl in mark_map:
    out.write('    .{ .mark = 0x%04X, .with = &.{ %s } },\n' % (m, ', '.join('0x%04X' % r for r in repl)))
out.write('};\n\n')
out.write('/// (base a, mark b) -> c, sorted by a then b.\n')
out.write('pub const compositions = [_]Pair{\n')
for a, b, c in compositions:
    out.write('    .{ .a = 0x%04X, .b = 0x%04X, .c = 0x%04X },\n' % (a, b, c))
out.write('};\n\n')
out.write('/// Letter a -> (base b, mark c), sorted by a.\n')
out.write('pub const decompositions = [_]Pair{\n')
for a, b, c in decompositions:
    out.write('    .{ .a = 0x%04X, .b = 0x%04X, .c = 0x%04X },\n' % (a, b, c))
out.write('};\n')
