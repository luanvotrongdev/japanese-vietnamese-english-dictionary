/// Removes HTML tags and decodes entities (twice, for double-escaped text),
/// then drops "nbsp" fragments and stray "&" left by Mazii's broken escaping
/// ("lẩu,&amp", "&amp;amp; nbsp"). Returns `s` itself when it has neither.
pub fn stripMarkup(a: Allocator, s: []const u8) ![]const u8 {
    if (std.mem.indexOfAny(u8, s, "<&") == null and std.mem.indexOf(u8, s, "nbsp") == null) return s;
    var t = try removeTags(a, s);
    t = try decodeEntities(a, t);
    t = try decodeEntities(a, t);
    return removeLeftovers(a, t);
}

fn removeTags(a: Allocator, s: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = try .initCapacity(a, s.len);
    var i: usize = 0;
    while (i < s.len) {
        if (s[i] == '<') {
            if (tagEnd(s, i)) |end| {
                // A line break separates text; other tags just disappear.
                const name = tagName(s, i);
                if (std.mem.eql(u8, name, "br") or std.mem.eql(u8, name, "div") or std.mem.eql(u8, name, "p") or std.mem.eql(u8, name, "li")) {
                    out.appendAssumeCapacity(' ');
                }
                i = end;
                continue;
            }
        }
        out.appendAssumeCapacity(s[i]);
        i += 1;
    }
    return out.items;
}

fn tagName(s: []const u8, start: usize) []const u8 {
    var i = start + 1;
    if (i < s.len and s[i] == '/') i += 1;
    while (i < s.len and s[i] == ' ') i += 1;
    const name_start = i;
    while (i < s.len and std.ascii.isLower(s[i])) i += 1;
    return s[name_start..i];
}

/// End (one past '>') of an HTML tag starting at `start`, or null when the
/// '<' does not start one of `html_tags`.
fn tagEnd(s: []const u8, start: usize) ?usize {
    const name = tagName(s, start);
    if (!html_tags.has(name)) return null;
    const after = @intFromPtr(name.ptr) - @intFromPtr(s.ptr) + name.len;
    if (after >= s.len or (s[after] != '>' and s[after] != ' ' and s[after] != '/')) return null;
    const close = std.mem.indexOfScalarPos(u8, s, after, '>') orelse return null;
    return close + 1;
}

fn decodeEntities(a: Allocator, s: []const u8) ![]const u8 {
    if (std.mem.indexOfScalar(u8, s, '&') == null) return s;
    var out: std.ArrayList(u8) = try .initCapacity(a, s.len + 8);
    var i: usize = 0;
    while (i < s.len) {
        if (s[i] == '&') {
            if (decodeEntity(s[i..])) |e| {
                switch (e.value) {
                    .text => |text| try out.appendSlice(a, text),
                    .codepoint => |c| {
                        var buf: [4]u8 = undefined;
                        const n = std.unicode.utf8Encode(c, &buf) catch 0;
                        try out.appendSlice(a, buf[0..n]);
                    },
                }
                i += e.len;
                continue;
            }
        }
        try out.append(a, s[i]);
        i += 1;
    }
    return out.items;
}

const Decoded = struct {
    value: union(enum) { text: []const u8, codepoint: u21 },
    /// Bytes the entity takes in the input.
    len: usize,
};

fn decodeEntity(s: []const u8) ?Decoded {
    var i: usize = 1;
    if (i < s.len and s[i] == '#') {
        i += 1;
        const hex = i < s.len and (s[i] == 'x' or s[i] == 'X');
        if (hex) i += 1;
        const digits_start = i;
        while (i < s.len and std.ascii.isHex(s[i])) i += 1;
        if (i == digits_start or i >= s.len or s[i] != ';') return null;
        const c = std.fmt.parseInt(u21, s[digits_start..i], if (hex) 16 else 10) catch return null;
        if (!std.unicode.utf8ValidCodepoint(c)) return null;
        return .{ .value = .{ .codepoint = c }, .len = i + 1 };
    }
    while (i < s.len and std.ascii.isAlphanumeric(s[i])) i += 1;
    const name = s[1..i];
    const text = entities.get(name) orelse return null;
    if (i < s.len and s[i] == ';') return .{ .value = .{ .text = text }, .len = i + 1 };
    // Mazii often drops the semicolon after these two, and the transform
    // splits glosses on ';', cutting it off at the end ("v&agrave").
    if (i == s.len or std.mem.eql(u8, name, "amp") or std.mem.eql(u8, name, "nbsp")) {
        return .{ .value = .{ .text = text }, .len = i };
    }
    return null;
}

fn isWordByte(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c >= 0x80;
}

/// A real "&" sits between two word characters (R&D) or two spaces (A & B).
fn keepAmpersand(s: []const u8, i: usize) bool {
    if (i == 0 or i + 1 >= s.len) return false;
    const before = s[i - 1];
    const after = s[i + 1];
    return (isWordByte(before) and isWordByte(after)) or (before == ' ' and after == ' ');
}

/// Drops the word "nbsp" and stray "&" left by broken escaping.
fn removeLeftovers(a: Allocator, s: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = try .initCapacity(a, s.len);
    var i: usize = 0;
    while (i < s.len) {
        if (std.mem.startsWith(u8, s[i..], "nbsp") and (i == 0 or !isWordByte(s[i - 1])) and
            (i + 4 == s.len or !isWordByte(s[i + 4])))
        {
            i += 4;
            continue;
        }
        if (s[i] == '&' and !keepAmpersand(s, i)) {
            i += 1;
            continue;
        }
        out.appendAssumeCapacity(s[i]);
        i += 1;
    }
    // Commas and semicolons that now sit next to each other or before a space.
    var j: usize = 0;
    var k: usize = 0;
    const b = out.items;
    while (j < b.len) : (j += 1) {
        if ((b[j] == ',' or b[j] == ';') and k > 0 and (b[k - 1] == ',' or b[k - 1] == ';')) continue;
        b[k] = b[j];
        k += 1;
    }
    return b[0..k];
}

/// Mazii sometimes splits a gloss right after a letter, leaving its accent
/// at the start of the next one ("\u{323}lưu").
fn dropLeadingMarks(s: []const u8) []const u8 {
    var rest = s;
    // U+0300–U+036F are CC 80–CC BF and CD 80–CD AF.
    while (rest.len >= 2 and ((rest[0] == 0xcc and rest[1] >= 0x80 and rest[1] <= 0xbf) or
        (rest[0] == 0xcd and rest[1] >= 0x80 and rest[1] <= 0xaf)))
    {
        rest = rest[2..];
    }
    return std.mem.trimStart(u8, rest, " ");
}

/// Removes the space Mazii leaves before punctuation ("Mèo con .").
pub fn tidy(a: Allocator, s: []const u8) ![]const u8 {
    if (std.mem.indexOfAny(u8, s, ".,;:!?") == null) return s;
    var out: std.ArrayList(u8) = try .initCapacity(a, s.len);
    for (s) |c| {
        if (std.mem.indexOfScalar(u8, ".,;:!?", c) != null) {
            while (out.items.len > 0 and out.items[out.items.len - 1] == ' ') out.items.len -= 1;
        }
        out.appendAssumeCapacity(c);
    }
    return out.items;
}

/// True when `s` has a letter or digit. Drops placeholder values like "*" or "_".
pub fn hasText(s: []const u8) bool {
    var it = (std.unicode.Utf8View.init(s) catch return s.len > 0).iterator();
    while (it.nextCodepoint()) |c| {
        if (c < 0x80) {
            if (std.ascii.isAlphanumeric(@intCast(c))) return true;
            continue;
        }
        const punctuation = (c >= 0x2000 and c <= 0x206f) or (c >= 0x3000 and c <= 0x3003) or
            (c >= 0x00a0 and c <= 0x00bf) or c == 0x00d7 or c == 0x00f7 or
            (c >= 0x0300 and c <= 0x036f) or c == 0x30fb or c == 0xfeff;
        if (!punctuation) return true;
    }
    return false;
}

fn isInvisible(ch: []const u8) bool {
    return std.mem.eql(u8, ch, "\u{200b}") or std.mem.eql(u8, ch, "\u{feff}") or std.mem.eql(u8, ch, "\u{ad}");
}

fn needsScrub(s: []const u8) bool {
    for (s) |c| if (c < 0x20 or c == 0x7f) return true;
    if (std.mem.indexOf(u8, s, "  ") != null) return true;
    return std.mem.indexOf(u8, s, "\u{200b}") != null or
        std.mem.indexOf(u8, s, "\u{feff}") != null or
        std.mem.indexOf(u8, s, "\u{ad}") != null;
}

// ---------------------------------------------------------------- NFC

fn isMark(c: u21) bool {
    return c >= 0x0300 and c <= 0x036f and table.combining_class[c - 0x0300] != 0;
}

fn ccc(c: u21) u8 {
    return table.combining_class[c - 0x0300];
}

/// Canonical composition (NFC) restricted to combining marks U+0300–U+036F.
/// Returns `s` itself when it has none of those marks or is not valid UTF-8.
pub fn nfc(a: Allocator, s: []const u8) ![]const u8 {
    // U+0300–U+036F are encoded as CC 80–CD AF.
    if (std.mem.indexOfScalar(u8, s, 0xcc) == null and std.mem.indexOfScalar(u8, s, 0xcd) == null) return s;
    const view = std.unicode.Utf8View.init(s) catch return s;

    var out: std.ArrayList(u8) = try .initCapacity(a, s.len);
    // The current segment: one starter and the marks after it.
    var segment: std.ArrayList(u21) = .empty;
    var it = view.iterator();
    while (it.nextCodepoint()) |c| {
        if (isMark(c) and segment.items.len > 0) {
            try appendMark(a, &segment, c);
            continue;
        }
        try flushSegment(a, &out, &segment);
        try segment.append(a, c);
    }
    try flushSegment(a, &out, &segment);
    return out.items;
}

fn appendMark(a: Allocator, segment: *std.ArrayList(u21), mark: u21) !void {
    for (table.mark_replacements) |r| {
        if (r.mark == mark) return segment.appendSlice(a, r.with);
    }
    try segment.append(a, mark);
}

/// Decomposes the starter, sorts the marks by combining class and composes
/// what can be composed, then writes the segment.
fn flushSegment(a: Allocator, out: *std.ArrayList(u8), segment: *std.ArrayList(u21)) !void {
    defer segment.clearRetainingCapacity();
    const items = segment.items;
    if (items.len == 0) return;
    if (items.len == 1) return appendCodepoint(a, out, items[0]);

    // Full decomposition of the starter, then its marks before the others.
    var marks: std.ArrayList(u21) = .empty;
    defer marks.deinit(a);
    var base = items[0];
    while (decompose(base)) |d| {
        try marks.insert(a, 0, d.c);
        base = d.b;
    }
    try marks.appendSlice(a, items[1..]);
    // Canonical ordering: stable sort by combining class.
    std.mem.sort(u21, marks.items, {}, struct {
        fn lt(_: void, x: u21, y: u21) bool {
            return ccc(x) < ccc(y);
        }
    }.lt);

    // Canonical composition: a mark composes with the starter unless an
    // uncomposed mark of the same or higher class sits between them.
    var kept: std.ArrayList(u21) = .empty;
    defer kept.deinit(a);
    var last_kept_class: u8 = 0;
    for (marks.items) |m| {
        const class = ccc(m);
        if (kept.items.len == 0 or last_kept_class < class) {
            if (compose(base, m)) |c| {
                base = c;
                continue;
            }
        }
        try kept.append(a, m);
        last_kept_class = class;
    }
    try appendCodepoint(a, out, base);
    for (kept.items) |m| try appendCodepoint(a, out, m);
}

fn appendCodepoint(a: Allocator, out: *std.ArrayList(u8), c: u21) !void {
    var buf: [4]u8 = undefined;
    const n = std.unicode.utf8Encode(c, &buf) catch return;
    try out.appendSlice(a, buf[0..n]);
}

fn compose(base: u21, mark: u21) ?u21 {
    const Key = struct { a: u21, b: u21 };
    const i = std.sort.binarySearch(table.Pair, &table.compositions, Key{ .a = base, .b = mark }, struct {
        fn order(k: Key, p: table.Pair) std.math.Order {
            if (k.a != p.a) return std.math.order(k.a, p.a);
            return std.math.order(k.b, p.b);
        }
    }.order) orelse return null;
    return table.compositions[i].c;
}

fn decompose(c: u21) ?table.Pair {
    const i = std.sort.binarySearch(table.Pair, &table.decompositions, c, struct {
        fn order(k: u21, p: table.Pair) std.math.Order {
            return std.math.order(k, p.a);
        }
    }.order) orelse return null;
    return table.decompositions[i];
}

// ---------------------------------------------------------------- tests

test "nfc composes Vietnamese accents" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const t = std.testing;
    // ư + U+0301 (acute), e + U+0302 + U+0301, a + U+0323 + U+0302 (dot below sorts first)
    try t.expectEqualStrings("ứ ế ậ", try nfc(a, "u\u{31b}\u{301} e\u{302}\u{301} a\u{323}\u{302}"));
    // Marks in the wrong order still compose in canonical order: ậ = a + dot below + circumflex.
    try t.expectEqualStrings("ậ", try nfc(a, "a\u{302}\u{323}"));
    // ê + U+0301 composes; U+0341 (from some keyboards) becomes an acute.
    try t.expectEqualStrings("ế ó", try nfc(a, "ê\u{301} o\u{341}"));
    // Two marks of the same class: the second stays separate, as in NFC.
    try t.expectEqualStrings("é\u{302}", try nfc(a, "e\u{301}\u{302}"));
    // Already composed text and Japanese are returned unchanged.
    const ja = "食べる ぶ ン゙";
    try t.expect((try nfc(a, ja)).ptr == ja.ptr);
    try t.expectEqualStrings("ăn uống", try nfc(a, "ăn uống"));
    // A mark with no starter is kept.
    try t.expectEqualStrings("\u{301}a", try nfc(a, "\u{301}a"));
}

test "clean removes invisible characters and line breaks" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const t = std.testing;
    try t.expectEqualStrings("ý kiến khác", try clean(a, "ý kiến \u{200b}\u{200b}khác"));
    try t.expectEqualStrings("không đáng tin cậy không đứng đắn", try clean(a, " không đáng tin cậy \r\n  không đứng đắn\n"));
    try t.expectEqualStrings("ab", try clean(a, "a\x08b\x10"));
    try t.expectEqualStrings("bánh", try clean(a, "ba\u{301}nh"));
    try t.expectEqualStrings("lưu", try clean(a, "\u{323}lưu"));
    try t.expectEqualStrings("chụp tia X", try clean(a, "chụp  tia X"));
}

test "clean removes Mazii markup" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const t = std.testing;
    try t.expectEqualStrings("Gãy, rỉ nước qua khe nứt", try clean(a, "Gãy, rỉ nước qua khe nứt<br><br>"));
    try t.expectEqualStrings("Đồng hồ đo điện trở Ohm", try clean(a, "<span style=\"color: rgb(0, 0, 245); \">Đồng hồ đo điện trở Ohm</span>"));
    try t.expectEqualStrings("thặng dư nhà sản xuất", try clean(a, "<b>thặng dư nhà sản xuất</ b><br>"));
    try t.expectEqualStrings("割引だね。", try clean(a, "<div>割引だね。<br></div>"));
    try t.expectEqualStrings("Sự vận động và thay đổi", try clean(a, "Sự vận động v&agrave; thay đổi"));
    try t.expectEqualStrings("ủng hộ thiếu úy", try clean(a, "ủng hộ thiếu úy&amp;amp; nbsp"));
    try t.expectEqualStrings("lẩu", try clean(a, "lẩu,&amp"));
    try t.expectEqualStrings("Sự vận động và", try clean(a, "Sự vận động v&agrave"));
    try t.expectEqualStrings("x&agravex", try clean(a, "x&agravex")); // not an entity name
    try t.expectEqualStrings("thanh toán minh bạch", try clean(a, "nbsp,&amp,thanh toán minh bạch"));
    try t.expectEqualStrings("rằng điểm số thấp.", try clean(a, "rằng&amp;nbsp; điểm số thấp."));
    try t.expectEqualStrings("CIF&I", try clean(a, "CIF&amp;I"));
    try t.expectEqualStrings("R&D", try clean(a, "R&D"));
    try t.expectEqualStrings("rock & roll", try clean(a, "rock &amp; roll"));
    try t.expectEqualStrings("a < b", try clean(a, "a &lt; b"));
    try t.expectEqualStrings("Đ", try clean(a, "&#272;"));
    // Subject labels from Mazii's source dictionary stay.
    try t.expectEqualStrings("<Y> dịch, thể dịch", try clean(a, "<Y>  dịch, thể dịch"));
    try t.expectEqualStrings("<PHẫU> âm hộ", try clean(a, "<PHẫU> âm hộ"));
    try t.expect(!hasText(try clean(a, "nbsp")));
    try t.expect(!hasText(try clean(a, "&amp")));
    try t.expectEqualStrings("Mèo con.", try tidy(a, "Mèo con ."));
    try t.expect(hasText("ăn"));
    try t.expect(hasText("食"));
    try t.expect(!hasText("*"));
    try t.expect(!hasText(" … "));
}
